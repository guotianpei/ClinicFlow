def _generator() -> ModuleType:
    """The serializer the oracle was written with (fixed code; never the new builder)."""

    path = HALOFLOW / "scripts" / "b1_premove_manifest.py"
    spec = importlib.util.spec_from_file_location("b1_premove_manifest", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _frozen() -> dict[str, Any]:
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def _synthetic() -> Any:
    from haloflow.synthetic import composition

    return composition


# --- B1-E0..E4: equality to the frozen oracle ----------------------------------------------


def test_b1_e0_frozen_manifest_is_the_committed_oracle() -> None:
    raw = MANIFEST.read_bytes()
    assert hashlib.sha256(raw).hexdigest() == MANIFEST_SHA256
    frozen = json.loads(raw)
    assert frozen["schema"] == "b1-premove-manifest/v1"
    assert frozen["source_commit"] == SOURCE_COMMIT
    assert frozen["registry"]["target_version"] == 94
    assert len(frozen["registry"]["units"]) == 94
    assert frozen["registry"]["migration_ids"] == [
        u["migration_id"] for u in frozen["registry"]["units"]]


def test_b1_e1_synthetic_registry_equals_the_frozen_registry() -> None:
    gen = _generator()
    actual = gen.registry_manifest(_synthetic().build_synthetic_registry())
    assert actual == _frozen()["registry"]


def test_b1_e2_synthetic_catalog_equals_the_frozen_catalog() -> None:
    gen = _generator()
    actual = gen.catalog_manifest(_synthetic().build_synthetic_catalog())
    assert actual == _frozen()["catalog"]


def test_b1_e3_test_profile_sql_equals_the_frozen_digests() -> None:
    gen = _generator()
